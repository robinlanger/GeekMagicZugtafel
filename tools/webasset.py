"""Minify, gzip and embed the device web assets (firmware/web/*) as a C++ header.

Pure functions, used by firmware/scripts/embed_web.py at build time and tested in
server/tests/test_webasset.py. No third-party dependencies.

The minifiers are deliberately conservative:
- CSS: comments go, whitespace collapses, spaces around { } : ; , > go. Quoted strings and
  url(...) stay byte for byte.
- JS: comments go (outside '...', "..." and `...`), each line is trimmed, blank lines go.
  Newlines stay, so automatic semicolon insertion still sees the same lines. Regex literals
  are not recognised: do not write a regex containing // or /* in firmware/web/app.js.
"""

from __future__ import annotations

import gzip
import hashlib
import re

_CSS_PUNCT = re.compile(r"\s*([{}:;,>])\s*")


def _css_chunks(src: str):
    """Yield (is_verbatim, text): strings and url(...) are verbatim, comments dropped."""
    i, n, buf = 0, len(src), []
    while i < n:
        c = src[i]
        if src.startswith("/*", i):
            end = src.find("*/", i + 2)
            i = n if end < 0 else end + 2
            buf.append(" ")
            continue
        if c in "\"'":
            j = i + 1
            while j < n and src[j] != c:
                j += 2 if src[j] == "\\" else 1
            yield False, "".join(buf)
            buf = []
            yield True, src[i : j + 1]
            i = j + 1
            continue
        if src.startswith("url(", i):
            end = src.find(")", i)
            end = n - 1 if end < 0 else end
            yield False, "".join(buf)
            buf = []
            yield True, src[i : end + 1]
            i = end + 1
            continue
        buf.append(c)
        i += 1
    yield False, "".join(buf)


def minify_css(src: str) -> str:
    out = []
    for verbatim, text in _css_chunks(src):
        if verbatim:
            out.append(text)
        else:
            text = re.sub(r"\s+", " ", text)
            out.append(_CSS_PUNCT.sub(r"\1", text))
    return "".join(out).strip()


def _strip_js_comments(src: str) -> str:
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        if c in "\"'`":
            j = i + 1
            while j < n and src[j] != c:
                j += 2 if src[j] == "\\" else 1
            out.append(src[i : j + 1])
            i = j + 1
        elif src.startswith("//", i):
            end = src.find("\n", i)
            i = n if end < 0 else end
        elif src.startswith("/*", i):
            end = src.find("*/", i + 2)
            i = n if end < 0 else end + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def minify_js(src: str) -> str:
    lines = (line.strip() for line in _strip_js_comments(src).splitlines())
    return "\n".join(line for line in lines if line)


def gzip_bytes(data: bytes) -> bytes:
    return gzip.compress(data, compresslevel=9, mtime=0)


def render_header(assets: dict[str, bytes]) -> str:
    digest = hashlib.sha256()
    lines = [
        "// Generated by firmware/scripts/embed_web.py from firmware/web/. Do not edit.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
    ]
    for name in sorted(assets):
        data = assets[name]
        digest.update(data)
        body = ",".join(f"0x{b:02x}" for b in data)
        lines.append(f"const uint8_t kWeb_{name}[] PROGMEM = {{{body}}};")
        lines.append(f"constexpr size_t kWeb_{name}Len = {len(data)};")
    lines.append(f'constexpr char kWebHash[] = "{digest.hexdigest()[:8]}";')
    return "\n".join(lines) + "\n"
