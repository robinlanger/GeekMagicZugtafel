"""Regenerate fixtures.h: server/.venv/bin/python firmware/test/test_tjpgd/make_fixtures.py"""
import io
from pathlib import Path

from PIL import Image, ImageDraw

img = Image.new("RGB", (240, 240))
d = ImageDraw.Draw(img)
for y in range(240):
    d.line([(0, y), (239, y)], fill=(y, 255 - y, (y * 3) % 256))
d.rectangle([16, 16, 111, 111], fill=(255, 0, 0))
d.rectangle([128, 128, 223, 223], fill=(0, 0, 255))
d.text((20, 180), "Glance Box 12:34", fill=(255, 255, 255))


def enc(**kw):
    b = io.BytesIO()
    img.save(b, "JPEG", quality=85, progressive=False, **kw)
    return b.getvalue()


fx = {
    "kServerStyle": enc(optimize=True),  # as server/glancebox/render.py
    "kStdTables444": enc(optimize=False, subsampling=0),  # standard Huffman tables, 4:4:4
    "kStdTables420": enc(optimize=False, subsampling=2),
}
out = [
    "// Generated by make_fixtures.py (Pillow): 240x240 gradient + red/blue squares,",
    "// quality 85, baseline. Do not edit.",
    "#pragma once",
    "#include <cstdint>",
    "",
]
for name, data in fx.items():
    out.append(f"// {len(data)} bytes")
    out.append(f"static const uint8_t {name}[] = {{")
    for i in range(0, len(data), 20):
        out.append("    " + ",".join(f"0x{b:02x}" for b in data[i : i + 20]) + ",")
    out.append("};")
Path(__file__).with_name("fixtures.h").write_text("\n".join(out) + "\n")
